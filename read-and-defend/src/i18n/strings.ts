export type StringKey = keyof Strings;
const TABLE: Record<LanguageCode, Strings> = { en, he };

let current: LanguageCode = 'en';
export const setUiLanguage = (l: LanguageCode) => { current = l; };
export const uiLanguage = () => current;

export function t<K extends StringKey>(key: K, vars?: Record<string, string | number>): Strings[K] {
  const v = TABLE[current][key];
  if (typeof v === 'string' && vars) {
    return v.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) as Strings[K];
  }
  return v;
}

export function tf(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export function stringsFor(l: LanguageCode): Strings { return TABLE[l]; }
